package com.mongodb.internal.annotations;

import java.lang.annotation.Documented;
import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * A sync method that is sync only by design although the generator's model reaches it (its async
 * half, if any, only throws): it gets no async twin, and the model does not pass it toward the
 * leaf. Placed by hand; the generator never writes or removes it.
 */
@Documented
@Target(ElementType.METHOD)
@Retention(RetentionPolicy.SOURCE)
public @interface NoAsync {
}
